/**
 * Returns 3-4 daily challenges deterministically based on today's date string YYYY-MM-DD
 */
export function getDailyChallengesForDate(dateStr: string): DailyChallenge[] {
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const absHash = Math.abs(hash);

  // Pick 3 or 4 distinct challenges
  const pool = [...PRESET_DAILY_CHALLENGES];
  const selected: DailyChallenge[] = [];
  const count = 3;

  for (let i = 0; i < count; i++) {
    const idx = (absHash + i * 3) % pool.length;
    selected.push(pool[idx]);
    pool.splice(idx, 1);
  }

  return selected;
}
