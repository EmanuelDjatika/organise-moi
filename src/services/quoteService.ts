const DECK_STORAGE_KEY = 'monorg_quote_deck_v2';

/**
 * Fisher-Yates shuffle algorithm
 */
function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Load remaining unshown deck of quotes from storage
 */
function getStoredDeck(): string[] {
  try {
    const raw = sessionStorage.getItem(DECK_STORAGE_KEY) || localStorage.getItem(DECK_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    // ignore parsing errors
  }
  return [];
}

/**
 * Persist remaining deck
 */
function saveDeck(deck: string[]): void {
  try {
    const json = JSON.stringify(deck);
    sessionStorage.setItem(DECK_STORAGE_KEY, json);
    localStorage.setItem(DECK_STORAGE_KEY, json);
  } catch (e) {
    // ignore
  }
}

/**
 * Get next guaranteed unique quote without repetition.
 * Uses a deck-shuffle mechanism so all 50+ quotes cycle completely before repeating,
 * and ensures the newly returned quote is never identical to currentQuote.
 */
export function getNextUniqueQuote(currentQuote?: string): string {
  let deck = getStoredDeck();

  // If deck is exhausted or invalid, regenerate a newly shuffled deck of all quotes
  if (deck.length === 0) {
    deck = shuffleArray(ORGANISATION_QUOTES);
  }

  // Ensure top of deck is not identical to currentQuote
  if (currentQuote && deck[0] === currentQuote && deck.length > 1) {
    // Swap with random position further down
    const swapIdx = 1 + Math.floor(Math.random() * (deck.length - 1));
    [deck[0], deck[swapIdx]] = [deck[swapIdx], deck[0]];
  }

  const selected = deck.shift() || ORGANISATION_QUOTES[0];
  saveDeck(deck);

  return selected;
}

/**
 * Fallback random quote that still avoids returning the same quote
 */
export function getRandomQuote(currentQuote?: string): string {
  return getNextUniqueQuote(currentQuote);
}
